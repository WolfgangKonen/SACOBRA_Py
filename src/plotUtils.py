import numpy as np
import pandas as pd
from matplotlib import pyplot as plt

from cobraInit import CobraInitializer
from gCOP import COP, GCOP


class PerformanceProfile:
    """
    **Performance profile** and **data profile** generator.

    Given a set :math:`P` of COPs (e.g. :math:`P` = {G01, G02, G03}) and a set :math:`S` of solvers :math:`s`.
    Performance and data profiles [MoreWild2009] are plots that allow to compare the different solvers :math:`s` on the
    given set :math:`P` of problems. We define :math:`t_{p,s}` as the lowest number of iterations in a run where a given
    convergence test is satisfied. In our context, the **convergence test** is (with :math:`f_{best}(t)`: best feasible
    objective value up to iteration :math:`t` and :math:`f_{opt}`: optimal feasible objective value):

      :math:`\\qquad f_{best}(t) - f_{opt} \leq \\tau`

    Performance and data profiles are defined as function of the **performance factor** (threshold) :math:`\\alpha`:

      :math:`\\qquad \\rho_s(\\alpha) = \\frac{1}{|P|}
      \\left|\\left\{ p \\in P | \\frac{t_{p,s}}{D(p)} \leq \\alpha\\right\}\\right|`

    where the denominator is :math:`D(p) = \\operatorname{min}_{s \\in S}(t_{p,s})` for **performance profiles** and
    :math:`D(p) = d_p + 1` for **data profiles** with :math:`d_p`: (input space) dimension of problem :math:`p`.

    The term :math:`\\rho_s(\\alpha)` measures how many percent of the problems a given solver :math:`s` solves within
    :math:`\\alpha\\cdot D(p)` iterations.

    Example usage::

        p_p = PerformanceProfile(tau=0.05)
        p_p.inject(dfsum, dir_run,"one_s", meth="one_s")
        p_p.inject(dfsum, dir_run,"solve", meth="solve")
        p_p.plot(range(0, 50, 2), f"{dir_run}/perf_DP.png", type="DP", ylim=[0, 1])
        p_p.plot(range(0, 50, 2), f"{dir_run}/perf_PP.png", type="PP", ylim=[0, 1])

    This example assumes that we have in ``dfsum`` the results of an experiment conducted with
    :meth:`.OneS.one_s_multi_g_r` and that the detailed results are in a subdirectory ``dir_run``.
    The corresponding data profile plot is shown below.

    [MoreWild2009] Moré J., Wild S. (2009) Benchmarking derivative-free optimization algorithms. SIAM J Optim
    20(1):172–191.
    """
    def __init__(self, tau=0.05):
        """

        :param tau: the tolerance level of the convergence test
        """
        self.ppsum = pd.DataFrame()
        self.solvers = []
        self.methods = []
        self.gnames = []
        self.meth = ""
        self.nruns = 0
        self.tau = tau

    def inject(self, dfsum: pd.DataFrame, dir_run: str, solver: str, meth: str, verbose=False):
        """
        Inject the results from a solver into ``self``. These results are usually generated by a call to
        :meth:`.OneS.one_s_multi_g_r`.

        :param dfsum:   data frame with summary results of experiment (see :meth:`.OneS.one_s_multi_g_r`)
        :param dir_run: subdirectory where further results of this experiment are stored
        :param solver:  name of the solver in this experiment
        :param meth:    use the rows with this ``meth`` from ``dfsum``
        :param verbose: if ``True``, print one line for each (gname-dim-meth) combination
        :return: ``True`` if injection was successful. The injection modifies the internal members of ``self``.
        """
        gnames = sorted(set(dfsum['gname'].values))
        if len(self.gnames) > 0:
            if gnames != self.gnames:
                print(f"[PerformanceProfile.update] WARNING: actual gnames = {gnames} differ from self.gnames = "
                      f"{self.gnames} for solver {solver}")
        self.gnames = gnames
        self.solvers += [solver]
        self.methods += [meth]
        self.meth = meth
        pp_solv = pd.DataFrame()
        for g in self.gnames:
            dims = sorted(set(dfsum[dfsum.gname == g]['d'].values))
            for d in dims:
                d = int(d)

                # obtain the optimal objective f_solu for this GCOP:
                df2 = pd.read_feather(f"{dir_run}/{g}_{d:02d}_{self.meth}_00_df2.feather")
                muFinal = df2.muVec.values[-1]
                gcop = GCOP(g, dimension=d, mu=muFinal)
                solu = gcop.solu
                if solu.ndim > 1:
                    solu = solu[0]
                f_solu = gcop.fn(solu)[0]

                z = dfsum[(dfsum.gname == g) & (dfsum.d == d) & (dfsum.meth == self.meth)]['err'].values
                self.nruns = len(z)
                for r in range(len(z)):
                    df1 = pd.read_feather(f"{dir_run}/{g}_{d:02d}_{self.meth}_{r:02d}_df1.feather")
                    df2 = pd.read_feather(f"{dir_run}/{g}_{d:02d}_{self.meth}_{r:02d}_df2.feather")

                    # This is only relevant for equality COPs with artificial feasibility enlargement:
                    # Invalidate the regions where muVec > muFinal (by setting fBest to 'fBest.max + 1000')
                    df2['trueNViol'] = df1.trueNViol[df2.iter.values[0]:].values
                    df2.loc[df2.muVec > muFinal, 'fBest'] = df2.fBest.max() + 1000

                    # A point is feasible if its predicate trueNViol is 0.
                    # We join column trueNViol from df1 to df2 (remember: df2 shorter by idp rows)
                    df2['trueNViol'] = df1.trueNViol[df2.iter.values[0]:].values

                    # compute t_p_s, the lowest iteration where this run is solved according to criterion crit
                    t_p_s, f_x_0 = self.compute_t_p_s(f_solu, df2, crit="ABS_DIFF")

                    if verbose:
                        print(f"{g} {d:2d} {r}: {f_x_0:7.2e} {df2.fBest.values[-1]:7.2e} {f_solu:7.2e} , "
                              f"{df2.muVec.values[-1]:7.4f}, {t_p_s:3.0f}")
                    adict = {'gname': g, 'dim': d, 'run': r, 'f_x_0': f_x_0, 'fbest': df2.fBest.values[-1],
                             'f_solu': f_solu, 'muFinal': muFinal, 't_p_s': t_p_s, 'meth': self.meth, 'solver': solver}
                    pp_solv = pd.concat([pp_solv, pd.DataFrame(adict, index=[0])])

        # add column 'min_t' ( needed for denominator in the case of performance profile, type="PP")
        if len(self.solvers) == 1:
            pp_solv['min_t'] = pp_solv.t_p_s
        else:       # i.e. len >= 2
            # if self.ppsum has already a column 'min_t', copy its *last* block (that with solver=self.solvers[-2])
            # to pp_solv and replace it then with the row-wise min of columns 't_p_s' and 'min_t'
            # (this copy will only work if all solvers operate on the same set of (gname-dim-run) combinations)
            pp_solv['min_t'] = self.ppsum[(self.ppsum.solver == self.solvers[-2])]['min_t']
            pp_solv['min_t'] = pp_solv[['t_p_s', 'min_t']].min(axis=1)
        self.ppsum = pd.concat([self.ppsum, pp_solv])
        return True

    def compute_t_p_s(self, f_solu, df2, crit="ABS_DIFF"):
        """ compute ``t_p_s``, the lowest iteration where this run is solved according to criterion ``crit`` """
        if crit == "ABS_DIFF":
            f_x_0 = np.nan
            t_p_s = df2[(df2.trueNViol == 0) & (df2.fBest - f_solu < self.tau)]['iter'].min()
        else:   # i.e. crit == "MORE_WILD"
            # f(x_0) should be the objective at the feasible starting point x_0. But we do not always have a feasible
            # starting point. We replace it here with the largest feasible objective found during optimization.
            largest_feasible = df2[df2.trueNViol == 0]['fBest'].max()
            f_x_0 = largest_feasible
            target = (1 - self.tau) * (f_x_0 - f_solu)
            t_p_s = df2[(df2.trueNViol == 0) & (f_x_0 - df2.fBest > target)]['iter'].min()

        if np.isnan(t_p_s):
            t_p_s = np.inf
        return t_p_s, f_x_0

    def plot(self, alpha_rng: range, png_file: str, ptype="DP", ylim: list | None = None):
        """
        Plot a performance profile or data profile and save it to ``pngfile``.

        :param alpha_rng: range of performance factor :math:`\\alpha`
        :param png_file:  where to save the plot
        :param ptype:     "PP" for performance profile, "DP" for data profile
        :param ylim:      limits for y-axis
        """
        colmar = ['bd-', 'g+-', 'rv-', 'k8-', 'cs-', 'm*-']
        # --- just debug analysis of values 't_p_s' ---
        # tval = sorted(set(self.ppsum['t_p_s'].values))
        # tmin = tval[0]
        # tmax = tval[-1]
        # if tmax == np.inf: tmax = tval[-2]
        # print(tmin, tmax)
        for s in self.solvers:
            tval = np.array(self.ppsum[self.ppsum.solver==s]['t_p_s'].values)
            n_solved = np.flatnonzero(np.array(tval) < np.inf).size
            g_unsolved = self.ppsum[(self.ppsum.solver==s) & (self.ppsum.t_p_s==np.inf)]['gname'].values
            g_s = ""
            for g in g_unsolved: g_s += g + " "
            sz = tval.size
            print(f"{s}: {n_solved} of {sz} ({n_solved/sz*100:5.1f}%) problems solved at tau={self.tau:5.3f}.")
            print(f"       Unsolved runs: {g_s}")

        if ptype == "DP":
            self.ppsum['crit'] = self.ppsum.t_p_s / (self.ppsum.dim + 1)
        elif ptype == "PP":
            # copy the 'min_t' values from the last-added solver ``solvers[-1]`` (it really contains min_s(t_{p,s}))
            # to the other solvers
            # (this copy will only work if all solvers operate on the same set of (gname-dim-run) combinations)
            for s in self.solvers:
                self.ppsum.loc[(self.ppsum.solver == s), 'min_t'] \
                    = self.ppsum[(self.ppsum.solver == self.solvers[-1])]['min_t']
            self.ppsum['crit'] = self.ppsum.t_p_s / self.ppsum.min_t
        else:
            raise RuntimeError(f"[PerformanceProfile.plot] type = {ptype} is not allowed (only 'DP' or 'PP')")

        plt.figure(figsize=(7, 6))  # (width,height) in inches
        for i, sol in enumerate(self.solvers):
            pp_sol = self.ppsum[(self.ppsum.solver == sol)]
            avec = []
            pvec = []
            for alpha in alpha_rng:
                avec += [alpha]
                # pp = self.ppsum[(self.ppsum.crit < alpha)]['crit'].values.size/len(self.ppsum)
                pp = pp_sol[(pp_sol.crit < alpha)]['crit'].values.size / len(pp_sol)
                pvec += [pp]
            plt.plot(avec, pvec, colmar[i % len(colmar)], label=sol)
        tit = "perf profile, " if ptype == "PP" else "data profile, "
        tit += r"$\tau=$" + f"{self.tau:5.2f}, {self.nruns} runs"      # pp_sol.meth.values[0] +
        plt.title(tit, fontsize=20)
        plt.xlabel(r"performance factor $\alpha$", fontsize=16)
        plt.ylabel("% of solved problems", fontsize=16)
        plt.legend()
        plt.grid(visible=True, which='major', axis='both', linewidth=0.5, color='0.7')
        plt.xticks(fontsize=14)
        plt.yticks(fontsize=14)
        if ylim is not None:
            plt.subplot(111).set(ylim=ylim)
        if png_file is not None:
            plt.savefig(png_file)
            print(f"performance profile saved to {png_file}")
        # plt.show()
        # plt.close()


def inner_plot(df: pd.DataFrame, muVec, gcop_fbest, gname, png_file, ylim=None, muFinal=None):
    """
        Helper function for show_error_plot and png_error_plot
    """
    # iteration number where we start plotting (after initialization phase)
    iStart = df.shape[0] - muVec.size
    err = df['fBest'].values[iStart:] - gcop_fbest
    plt.figure(figsize=(7, 6))  # (width,height) in inches
    plt.plot(range(iStart, iStart + err.size), np.abs(err), 'r-', label='error')
    if np.max(muVec) > 0:
        # for equality-constrained COPs: Collect in ind_blue the indices where artificial feasibility takes place. Store
        # in jumps the borders of consecutive-indices regions. Then overplot each region with consecutive indices in
        # blue:
        if muFinal is None:
            muFinal = muVec[-1]         # we assume that muVec[-1] == sac_opts.EQU.muFinal
        ind_blue = np.flatnonzero(muVec > muFinal)
        delta = ind_blue - np.roll(ind_blue, 1) - 1
        jumps = np.flatnonzero(delta > 0)
        jumps = np.concat((jumps, np.array([ind_blue.size])))
        j_start = 0
        for k in range(jumps.size):
            ind_k = ind_blue[j_start:jumps[k]]
            if ind_blue[j_start] > 0:
                # add 'one index earlier' to paint also the upwards shoulder of the jump in blue:
                ind_k = np.array([ind_blue[j_start]-1] + list(ind_blue[j_start:jumps[k]]))
            plt.plot(iStart + ind_k, np.abs(err[ind_k]), 'b-', label='error')
            j_start = jumps[k]
    plt.title(gname, fontsize=20)
    plt.xlabel('func evals ', fontsize=16)
    plt.ylabel('error', fontsize=16)
    plt.xticks(fontsize=14)
    plt.yticks(fontsize=14)
    plt.subplot(111).set_yscale("log")
    if ylim is not None:
        plt.subplot(111).set(ylim=ylim)
    # else:     # option to make an automatic ylim, but this is normally done as default (plotting w/o ylim)
    #     ylim0 = 10**np.floor(np.log10(min(err)))
    #     ylim1 = 10**np.ceil(np.log10(max(err)))
    #     plt.subplot(111).set(ylim=[ylim0,ylim1])
    if png_file is not None:
        plt.savefig(png_file)
        print(f"error plot saved to {png_file}")


def show_error_plot(cobra: CobraInitializer, cop: COP, muVec, muFinal=None, ylim=None, file=None):
    """
    Show a logarithmic error curve plot and save it to ``png_file``.

    Details: Plots only the iterations after SACOBRA initialization. Overplots the regions of artificial feasibility
    (error may be rising) in blue. Only the regions plotted in red are truly feasible (``muFinal``). Artificial
    feasibility occurs only for COPs with equality constraints.

    :param cobra: contains data frame with column ``df['fBest']`` carrying the best feasible objective value obtained up to iteration ``iter``
    :param cop:   contains fbest, the true best objective value, and name, the problem name
    :param muVec: values of ``currentMu`` (for all iterations after SACOBRA initialization)
    :param muFinal: only in regions with ``muVec=muFinal`` an artificially feasible point is also truly feasible. If
                    ``muFinal=None``, it is inferred from the last element ``muVec[-1]``
    :param ylim:  (optional) limits for the y-axis
    :param file:  (optional) where to save the plot as PNG
    """
    inner_plot(cobra.df, muVec, cop.fbest, cop.name, file, ylim, muFinal)
    # err = cobra.sac_res['fbestArray'] - cop.fbest
    plt.show()
    plt.close()


def png_error_plot(df: pd.DataFrame, muVec, gcop_fbest, gname, png_file, muFinal=None, ylim=None):
    """
    Make a logarithmic error curve plot and save it to ``png_file``.

    Details: Plots only the iterations after SACOBRA initialization. Overplots the regions of artificial feasibility
    (error may be rising) in blue. Only the regions plotted in red are truly feasible (``muFinal``). Artificial
    feasibility occurs only for COPs with equality constraints.

    :param df:      data frame with  column ``df['fBest']`` carrying the best feasible objective value obtained up to iteration ``iter``
    :param muVec:   values of ``currentMu`` (for all iterations after SACOBRA initialization)
    :param gcop_fbest: the true best objective value
    :param gname:   the name of the problem
    :param png_file:   where to save the PNG
    :param muFinal: only in regions with ``df.muVec=muFinal`` an artificially feasible point is also truly feasible. If
                    ``muFinal=None``, it is inferred from the last element ``df.muVec[-1]``
    :param ylim:    (optional) limits for the y-axis
    """
    inner_plot(df, muVec, gcop_fbest, gname, png_file, ylim, muFinal)
    plt.close()


def png_boxplot_errs(dfsum: pd.DataFrame, tit: str, png_file: str, meth=None, ylim=None):
    """
    Make a group of boxplots of errors on a logarithmic y-axis and save it to ``png_file``.

    :param dfsum:   data frame: column ``err`` carries the errors and column ``gname`` the problem name
    :param tit:     title prefix, will be appended by ``meth`` (if not ``None``) and number of runs
    :param png_file:  where to save the PNG
    :param meth:    (optional) if ``'one_s'`` or ``'solve'``, plot only those errors with ``dfsum['meth']==meth``
    :param ylim:    (optional) ``[ylow,yhigh]`` limits for y-axis
    """
    gnames = sorted(set(dfsum['gname'].values))
    errs2 = []
    labels2 = []
    for g in gnames:
        dims = sorted(set(dfsum[dfsum.gname == g]['d'].values))
        # errs2 += [dfsum[(dfsum.gname==g) & (dfsum.d==d)]['err'].values for d in dims]
        if meth is None:
            z = [dfsum[(dfsum.gname == g) & (dfsum.d == d)]['err'].values for d in dims]
        else:
            z = [dfsum[(dfsum.gname == g) & (dfsum.d == d) & (dfsum.meth == meth)]['err'].values for d in dims]
        # z is now a list of N sub-lists, each sub-list with M error values, where
        # N = len(dims) (possible values for d)
        # M = number of runs (rows in dfsum) with this (g, d [,meth])-combination
        if np.min(np.array(z)) < 0:
            print(f"[png_boxplot_errs] WARNING: negative errors in problem {g}")
        if np.any(np.isnan(z)):
            for i in range(len(z[0])):
                if np.isnan(z[0][i]): z[0][i] = -1
            print(f"[png_boxplot_errs] WARNING: NaN's in problem {g} --> replacing them with -1")
        errs2 += z
        if len(dims) == 1:
            labels2 += [g]
        else:
            labels2 += [g + '-'+str(d) for d in dims]
    colors = ['peachpuff', 'orange', 'tomato', 'peachpuff', 'orange', 'tomato', 'peachpuff', 'orange', 'tomato',
              'peachpuff', 'orange', 'tomato', 'peachpuff', 'orange', 'tomato', 'peachpuff', 'orange', 'tomato',
              'peachpuff', 'orange', 'tomato', 'peachpuff', 'orange', 'tomato', 'peachpuff', 'orange', 'tomato',]
    fig, ax = plt.subplots(figsize=(14, 6))
    bplot = ax.boxplot(errs2,
                       patch_artist=True,  # fill with color
                       medianprops={"color": "black", "linewidth": 0.5},
                       tick_labels=labels2)  # will be used to label x-ticks
    # fill with colors
    for patch, color in zip(bplot['boxes'], colors):
        patch.set_facecolor(color)

    meth_str = "" if meth is None else ', ' + meth
    nruns = len(errs2[0])   # 0 if errs2.size == 0 else errs2[0].size
    plt.title(f"{tit}{meth_str}, {nruns} runs", fontsize=20)
    plt.xlabel('problem', fontsize=16)
    plt.ylabel('error', fontsize=16)
    plt.xticks(fontsize=14)
    plt.yticks(fontsize=14)
    plt.subplot(111).set_yscale("log")
    if ylim is not None:
        plt.subplot(111).set(ylim=ylim)
    if png_file is not None:
        plt.savefig(png_file)
        print(f"png_boxplot_errs saved to {png_file}")
    # plt.show()
